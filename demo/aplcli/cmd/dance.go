// danceCmd represents the dance command
var danceCmd = &cobra.Command{
	Use:   "dance",
	Short: "Dancing Reindeer",
	Run: func(cmd *cobra.Command, args []string) {
		duration := viper.GetInt("duration")
		fmt.Printf("\nDance duration is: %d seconds\n", duration)

		for i := 1; i <= duration; i++ {
			// print left dancing Reindeer
			time.Sleep(500 * time.Millisecond)
			fmt.Printf("%s\r", danceLeft)
			fmt.Print("\033[14A")

			// print right dancing Reindeer
			time.Sleep(500 * time.Millisecond)
			fmt.Printf("%s\r", danceRight)
			fmt.Print("\033[14A")
		}

		fmt.Print(strings.Repeat("\n", 15))
	},
}

func init() {
	rootCmd.AddCommand(danceCmd)

	danceCmd.Flags().IntP("duration", "d", 10, "Time in seconds for Reindeer to dance")
	_ = viper.BindPFlags(danceCmd.LocalFlags())
}
